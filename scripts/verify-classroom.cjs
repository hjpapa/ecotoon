const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const scope={TextEncoder};vm.createContext(scope);
vm.runInContext(fs.readFileSync(path.join(root,'classroom-store.js'),'utf8'),scope);
const api=scope.ClassroomStorage;
const stories=vm.runInNewContext(fs.readFileSync(path.join(root,'catalog.js'),'utf8')+';STORIES');
function memory(seed={}){const map=new Map(Object.entries(seed));return {getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};}
const saved={'g1-01':{read:true,quiz:true,note:'이전 기록',gameDone:true,gameStars:3}};
const storage=memory({'ecotoon-progress-v3':JSON.stringify(saved)});
let store=api.create(storage,stories);
assert.equal(JSON.stringify(store.current().records),JSON.stringify(saved));
store.add('달토끼','🐰');const rabbit=store.current().id;
assert.equal(Object.keys(store.current().records).length,0);
assert.equal(storage.getItem('ecotoon-progress-v3'),null,'Remove old copies only after atomic migration');
assert.equal(store.save({'g1-02':{read:true,note:'토끼 기록'}}),true);
store.select('original');assert.equal(store.current().records['g1-01'].gameStars,3);
store.select(rabbit);const file=store.export();
store=api.create(storage,stories);assert.equal(store.current().name,'달토끼');
assert.equal(store.current().records['g1-02'].note,'토끼 기록');
store.import(file,'별토끼');assert.equal(store.current().records['g1-02'].note,'토끼 기록');
store.clear();assert.equal(Object.keys(store.current().records).length,0);
store.remove();store.select(rabbit);assert.equal(store.current().records['g1-02'].note,'토끼 기록');
store.rename('숲토끼','🌱');assert.equal(store.current().name,'숲토끼');
const original=JSON.parse(file);
for(const invalid of ['{',JSON.stringify({...original,version:2}),JSON.stringify({...original,records:{bad:{read:true}}}),JSON.stringify({...original,records:{'g1-01':{read:'true'}}}),JSON.stringify({...original,records:{'g1-01':{gameStars:4}}}),JSON.stringify({...original,records:{'g1-01':{note:7}}}),JSON.stringify({...original,records:JSON.parse('{"__proto__":{}}')}),' '.repeat(api.MAX_FILE+1)]){
 const before=storage.getItem(api.KEY);assert.throws(()=>store.import(invalid,'잘못된 파일'));assert.equal(storage.getItem(api.KEY),before);
}
assert.throws(()=>store.add('숲토끼','🐰'));assert.throws(()=>store.add('','🐰'));assert.throws(()=>store.add('가'.repeat(13),'🐰'));
const another=api.create(storage,stories);store.select('original');
assert.equal(another.save({'g1-03':{note:'충돌 기록'}}),false);
assert.ok(another.issue().includes('다른 탭'));
assert.equal(another.current().records['g1-03'].note,'충돌 기록','Keep unsaved work exportable');
assert.equal(api.create(storage,stories).current().id,'original','Stale tab cannot switch or overwrite');
const unavailable=api.create({getItem(){throw Error('blocked')}},stories);
assert.equal(unavailable.save(saved),false);assert.equal(JSON.parse(unavailable.export()).records['g1-01'].note,'이전 기록');
const full=memory();const limited=api.create(full,stories);full.setItem=()=>{throw Error('quota')};
assert.throws(()=>limited.add('새 별명','🐻'));assert.equal(limited.list().length,1);assert.equal(limited.save(saved),false);
const corrupt=memory({[api.KEY]:'{broken'});const protectedStore=api.create(corrupt,stories);
assert.equal(protectedStore.save(saved),false);assert.equal(corrupt.getItem(api.KEY),'{broken');
const legacy=api.create(memory({'ecotoon-progress':JSON.stringify({0:{read:true,note:'옛 메모'},20:{quiz:true,note:'겹친 메모'}})}),stories);
assert.equal(legacy.current().records['g1-01'].note,'옛 메모');
const overlap=api.create(memory({'ecotoon-progress':JSON.stringify({4:{read:true,note:'첫 기록'},22:{quiz:true,note:'둘째 기록'}})}),stories);
assert.equal(overlap.current().records[stories[20].id].note,'첫 기록\n\n둘째 기록');
assert.equal(overlap.current().records[stories[20].id].read,true);assert.equal(overlap.current().records[stories[20].id].quiz,true);
const longNote='가'.repeat(12000);
const longStore=api.create(memory({'ecotoon-progress-v3':JSON.stringify({'g1-01':{note:longNote}})}),stories);
assert.equal(longStore.parse(longStore.export()).records['g1-01'].note,longNote,'Keep old long notes intact');
const many=api.create(memory(),stories);for(let i=1;i<30;i++)many.add('별명'+i,'⭐');assert.throws(()=>many.add('마지막','⭐'));
console.log('PASS: legacy/v3 migration, isolated profiles, reload, rename, JSON round trip, strict invalid-file rejection, clear/delete, quota/blocked/corrupt storage and stale-tab conflict protection.');
